# :public_key PEM and X.509 decoding of the TLS fixture certificates (tests/cases/ssl/).
dir = "tests/cases/ssl/"
pem = File.read!(dir <> "server.pem")
[{:Certificate, der, :not_encrypted} = entry] = :public_key.pem_decode(pem)
IO.inspect(byte_size(der), label: "der size")
plain = :public_key.pem_entry_decode(entry)
IO.inspect(plain, label: "plain", limit: :infinity)
IO.inspect(plain == :public_key.pkix_decode_cert(der, :plain), label: "same")
otp = :public_key.pkix_decode_cert(der, :otp)
{:OTPCertificate, tbs, sigalg, sig} = otp
IO.inspect(sigalg, label: "otp sigalg")
IO.inspect(byte_size(sig), label: "sig")
tbs |> Tuple.to_list() |> Enum.take(10) |> IO.inspect(label: "otp tbs", limit: :infinity)
[{:PrivateKeyInfo, kder, :not_encrypted} = k] = :public_key.pem_decode(File.read!(dir <> "serverkey.pem"))
IO.inspect(byte_size(kder), label: "key der")
key = :public_key.pem_entry_decode(k)
IO.inspect(elem(key, 0), label: "key type")
IO.inspect(elem(key, 1), label: "key version")
IO.inspect(elem(key, 3), label: "key curve")
IO.inspect(:public_key.pem_encode([entry]) == pem, label: "pem roundtrip")
f = :public_key.pkix_verify_hostname_match_fun(:https)
IO.inspect(f.({:dns_id, ~c"www.example.com"}, {:dNSName, ~c"*.example.com"}), label: "wild")
IO.inspect(f.({:dns_id, ~c"www.example.com"}, {:dNSName, ~c"*.other.com"}), label: "wild other")
IO.inspect(f.({:ip, ~c"1.2.3.4"}, {:iPAddress, [1, 2, 3, 4]}), label: "default")
IO.inspect(:ssl.str_to_suite(~c"ECDHE-ECDSA-AES256-GCM-SHA384"), label: "str_to_suite")
IO.inspect(:ssl.suite_to_str(%{key_exchange: :ecdhe_rsa, cipher: :aes_128_gcm, mac: :aead, prf: :sha256}), label: "suite_to_str")
IO.inspect(Application.spec(:ssl, :vsn), label: "ssl vsn")
