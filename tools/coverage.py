#!/usr/bin/env python3
"""Compare declared Tonic exports with pinned Elixir/OTP exports and reviewed evidence."""
import argparse
from collections import Counter, defaultdict
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
REFERENCE = ROOT / "tests/coverage/reference.json"
RULES = ROOT / "tests/coverage/rules.json"
STATES = {"implemented", "partial", "unsupported", "different"}


def key(row):
    return row["module"], row["name"], row["arity"], row["kind"]


def read_json(command):
    result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, timeout=300)
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or f"command failed: {command}")
    return json.loads(result.stdout)


def serialize(data):
    metadata = {name: value for name, value in data.items() if name != "exports"}
    entries = ",\n".join("    " + json.dumps(row, sort_keys=True, separators=(",", ":"))
                          for row in data["exports"])
    return json.dumps(metadata, indent=2)[:-2] + ',\n  "exports": [\n' + entries + "\n  ]\n}\n"


def fingerprint():
    digest = hashlib.sha256()
    for directory in ["compiler", "runtime", "shared", "lib", "mix", "tests"]:
        for path in sorted((ROOT / directory).rglob("*")):
            if path.suffix not in {".rs", ".ex", ".exs", ".erl", ".out", ".json"}:
                continue
            if any(part in {"target", "_build", "deps"} for part in path.parts):
                continue
            digest.update(str(path.relative_to(ROOT)).encode() + b"\0" + path.read_bytes())
    return digest.hexdigest()


def validate_evidence(rule, label):
    if rule.get("status") not in STATES or not rule.get("reason"):
        raise ValueError(f"missing status/reason: {label}")
    tests = rule.get("tests", [])
    if rule["status"] == "implemented" and not tests:
        raise ValueError(f"implemented API needs a declaration and regression: {label}")
    for test in tests:
        path = ROOT / test.split("#", 1)[0]
        if not path.is_file() or not str(path.relative_to(ROOT)).startswith(("tests/", "compiler/tests/", "runtime/tests/", "mix/tests/")):
            raise ValueError(f"missing regression: {test}")
        if "#" in test and test.split("#", 1)[1] not in path.read_text():
            raise ValueError(f"missing test name: {test}")


def report(native, reference, rules):
    if reference["elixir"] != "1.18.3" or reference["otp"] != "27":
        raise ValueError("reference must be Elixir 1.18.3 / OTP 27")
    upstream = {key(row): row for row in reference["exports"]}
    declared = {key(row): row for row in native["exports"]
                if row["name"] not in {"module_info", "__info__"}}
    reviewed = {}
    for rule in rules["apis"]:
        entry = key(rule)
        if entry in reviewed or entry not in upstream.keys() | declared.keys():
            raise ValueError(f"duplicate or unknown reviewed API: {entry}")
        validate_evidence(rule, entry)
        tests = rule.get("tests", [])
        if rule["status"] == "implemented" and (not tests or entry not in declared):
            raise ValueError(f"implemented API needs a declaration and regression: {entry}")
        reviewed[entry] = rule
    capabilities = rules.get("capabilities", [])
    names = set()
    for capability in capabilities:
        name = capability["name"]
        if name in names:
            raise ValueError(f"duplicate capability: {name}")
        names.add(name)
        validate_evidence(capability, name)
    rows = []
    for entry in sorted(upstream.keys() | declared.keys()):
        base = upstream.get(entry, declared.get(entry))
        present = entry in declared
        row = {field: base[field] for field in ["module", "name", "arity", "kind"]}
        row.update(reference=entry in upstream, declared=present,
                   status="partial" if present else "unsupported", tests=[])
        if present:
            row["source"] = declared[entry]["source"]
        rule = reviewed.get(entry)
        if rule:
            row.update({field: rule[field] for field in ["status", "reason", "tests"] if field in rule})
            row["reviewed"] = True
        rows.append(row)
    return {"schema": 1, "tonic": native["version"],
            "reference": {k: v for k, v in reference.items() if k != "exports"},
            "source_sha256": fingerprint(), "summary": dict(Counter(row["status"] for row in rows)),
            "capabilities": capabilities, "exports": rows}


def markdown(data):
    counts = data["summary"]
    lines = ["# API conformance inventory", "",
             "Generated by `python3 tools/coverage.py`. Source: `tonic inventory`, the pinned",
             "reference export snapshot, and reviewed rules in `tests/coverage/rules.json`.", "",
             "The reference is Elixir 1.18.3 / OTP 27. The snapshot records its ERTS version",
             "and application scope in [coverage.json](coverage.json). It includes exported",
             "functions and macros, including internal application modules. Compiler language",
             "forms and runtime capabilities need their own conformance tests; API counts",
             "are not a percentage of Elixir compatibility.", "",
             "An exported declaration defaults to **partial**. Presence, imported upstream",
             "source, and successful compilation alone never establish semantic parity.",
             "**Implemented** means a reviewed implementation with linked regression evidence;",
             "the evidence is bounded by those tests. **Different** records an observed",
             "semantic difference. **Unsupported** means absent or explicitly reviewed as",
             "unavailable. `reference: false` marks exports outside this reference snapshot;",
             "it does not establish that an API is unique to Tonic.", "",
             "| Status | Exports |", "| --- | ---: |"]
    lines += [f"| {state} | {counts.get(state, 0)} |" for state in sorted(STATES)]
    lines += ["", "## Runtime and compiler capabilities", "",
              "These classifications are separate from export counts.", "",
              "| Capability | Status | Scope and evidence |", "| --- | --- | --- |"]
    for capability in data["capabilities"]:
        evidence = "; ".join(f"[{test}](../{test.split('#', 1)[0]})" for test in capability.get("tests", []))
        lines.append(f"| {capability['name']} | {capability['status']} | {capability['reason']} {evidence} |")
    lines += ["", "## Reviewed evidence", "", "| API | Status | Evidence |", "| --- | --- | --- |"]
    for row in data["exports"]:
        if not row.get("reviewed"):
            continue
        api = f"{row['module']}.{row['name']}/{row['arity']} ({row['kind']})".replace("|", "\\|")
        evidence = "; ".join(f"[{test}](../{test.split('#', 1)[0]})" for test in row["tests"])
        lines.append(f"| `{api}` | {row['status']} | {evidence or row['reason']} |")
    modules = defaultdict(Counter)
    for row in data["exports"]:
        modules[row["module"]][row["status"]] += 1
    lines += ["", "## Module summary", "",
              "| Module | Implemented | Partial | Different | Unsupported |",
              "| --- | ---: | ---: | ---: | ---: |"]
    for module, counts in sorted(modules.items()):
        lines.append(f"| `{module}` | {counts['implemented']} | {counts['partial']} | {counts['different']} | {counts['unsupported']} |")
    lines += ["", "## Refresh and verification", "", "```sh",
              "cargo build --workspace --locked",
              "python3 tools/coverage.py --refresh-reference",
              "python3 tools/coverage.py --check", "```", "",
              "Refreshing the reference requires installed Elixir 1.18.3 / OTP 27.",
              "Ordinary generation and `--check` reuse the checked-in snapshot and inspect",
              "the current native declarations. The default command builds the local compiler",
              "through Cargo; `--tonic` selects an explicit binary that must match the source.",
              "They do not download Hex packages or start OTP",
              "applications. Source fingerprints detect changes that require regeneration.", "",
              "Run the linked regressions separately; generation does not execute them.",
              "Update reviewed rules when behavior changes, then regenerate both this",
              "inventory and the documentation context with `python3 tools/context.py`.", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tonic", help="explicit compiler binary (must match the current source)")
    parser.add_argument("--refresh-reference", action="store_true")
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    if options.check and options.refresh_reference:
        parser.error("--check cannot refresh the reference")
    if options.refresh_reference:
        snapshot = read_json([os.environ.get("ELIXIR", "elixir"), "tools/reference.exs"])
        if snapshot["elixir"] != "1.18.3" or snapshot["otp"] != "27":
            parser.error("reference must be Elixir 1.18.3 / OTP 27")
        REFERENCE.write_text(serialize(snapshot))
    command = [options.tonic, "inventory"] if options.tonic else [
        "cargo", "run", "--quiet", "--locked", "--bin", "tonic", "--", "inventory"]
    data = report(read_json(command), json.loads(REFERENCE.read_text()),
                  json.loads(RULES.read_text()))
    outputs = {"docs/coverage.json": serialize(data),
               "docs/coverage.md": markdown(data)}
    for name, content in outputs.items():
        path = ROOT / name
        if options.check:
            if not path.is_file() or path.read_text() != content:
                raise ValueError(f"stale {name}; run python3 tools/coverage.py")
        else:
            path.write_text(content)
    print("conformance inventory is current" if options.check else "generated conformance inventory")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, RuntimeError, OSError, subprocess.TimeoutExpired) as error:
        sys.exit(str(error))
