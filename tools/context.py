#!/usr/bin/env python3
"""Generate plain-text context and published Markdown from repository docs."""
import argparse
from pathlib import Path
import re
import sys
from urllib.parse import urljoin

ROOT = Path(__file__).resolve().parent.parent
REPO = "https://github.com/wess/tonic/blob/main/"
PAGES = {
    "docs/semantics.md": "docs/semantics.md",
    "README.md": "index.md",
    "docs/compatibility.md": "docs/compatibility.md",
    "TODO.md": "roadmap.md",
    "docs/release.md": "docs/release.md",
    "docs/coverage.md": "docs/coverage.md",
}


def markdown(source):
    text = (ROOT / source).read_text(encoding="utf-8").strip()
    # published pages and the combined context need repository-relative links resolved
    return re.sub(r"(\]\()([^\s)]+)(\))",
                  lambda match: match[1] + urljoin(REPO + source, match[2]) + match[3], text)


def outputs():
    index = (ROOT / "llms.txt").read_text(encoding="utf-8")
    pages = {source: markdown(source) + "\n" for source in PAGES}
    sections = ["# Tonic complete context\n\n"
                "Generated by `python3 tools/context.py` from repository documentation.\n"
                "Edit the source documents and regenerate; do not edit this file directly.\n"
                "Upstream Elixir and OTP references are linked, not bundled.\n",
                "Source: " + REPO + "llms.txt\n\n" + index]
    for source, content in pages.items():
        if source not in {"docs/release.md", "docs/coverage.md"}:
            sections.append("Source: " + REPO + source + "\n\n" + content)
    full = "\n---\n\n".join(sections)
    result = {"llm.txt": index, "llmsfull.txt": full,
              "site/llms.txt": index, "site/llm.txt": index, "site/llmsfull.txt": full}
    result.update({"site/" + target: pages[source] for source, target in PAGES.items()})
    result["site/docs/coverage.json"] = (ROOT / "docs/coverage.json").read_text(encoding="utf-8")
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    options = parser.parse_args()
    stale = []
    for name, content in outputs().items():
        path = ROOT / name
        if options.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        print("stale context: " + ", ".join(stale), file=sys.stderr)
        print("run python3 tools/context.py", file=sys.stderr)
        return 1
    print("context is current" if options.check else "generated context and published Markdown")
    return 0


if __name__ == "__main__":
    sys.exit(main())
